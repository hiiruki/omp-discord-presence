#!/usr/bin/env bun
/**
 * Regenerates the model logos from lobe-icons (https://github.com/lobehub/lobe-icons) for every model in
 * omp's bundled catalog:
 *
 * - extensions/model-icons.generated.ts: lobe's model/provider keyword rules, in lobe's order
 * - assets/models/<key>.png: one logo per icon an omp model resolves to (upload these as Discord Art Assets)
 *
 * Run after bumping LOBE_ICONS_VERSION / STATIC_PNG_VERSION or updating @oh-my-pi/pi-catalog:
 *   bun scripts/sync-model-icons.ts
 */
import { getBundledModels, getBundledProviders } from "@oh-my-pi/pi-catalog";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const LOBE_ICONS_VERSION = "6.13.0";
const STATIC_PNG_VERSION = "2.5.0";
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ASSETS_DIR = join(ROOT, "assets/models");
const GENERATED_FILE = join(ROOT, "extensions/model-icons.generated.ts");
// Discord allows 300 Art Assets per application.
const MAX_ASSETS = 300;

type Rule = { keywords: string[]; icon: string };

const fetchText = async (url: string): Promise<string> => {
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
	return response.text();
};

/** Parses lobe's compiled `modelMappings` / `providerMappings` into keyword rules naming the icon directory. */
const parseLobeMappings = (source: string, exportName: string): Rule[] => {
	const icons = new Map<string, string>();
	for (const [, binding, dir] of source.matchAll(/import (Icons(?:\$\d+)?) from "\.\.\/([^/]+)\/index\.mjs";/g)) {
		icons.set(binding!, dir!);
	}
	const body = source.match(new RegExp(`const ${exportName} = (\\[[\\s\\S]*?\\n\\]);`))?.[1];
	if (!body || icons.size === 0) throw new Error(`could not find ${exportName} in lobe-icons ${LOBE_ICONS_VERSION}`);
	const rules: Rule[] = [];
	for (const [, binding, keywords] of body.matchAll(/Icon: (Icons(?:\$\d+)?),\s*keywords: (\[[^\]]*\])/g)) {
		const icon = icons.get(binding!);
		if (!icon) throw new Error(`unknown icon binding ${binding}`);
		rules.push({ icon, keywords: JSON.parse(keywords!.replace(/,\s*\]/, "]")) as string[] });
	}
	return rules;
};

// Same semantics as lobe's ModelIcon: first rule whose keyword regex matches the lowercased id, case-insensitive.
const match = (rules: Rule[], value: string): Rule | undefined =>
	rules.find((rule) => rule.keywords.some((keyword) => new RegExp(keyword, "i").test(value.toLowerCase())));

const base = `https://cdn.jsdelivr.net/npm/@lobehub/icons@${LOBE_ICONS_VERSION}/es/features`;
const modelRules = parseLobeMappings(await fetchText(`${base}/modelConfig.mjs`), "modelMappings");
const providerRules = parseLobeMappings(await fetchText(`${base}/providerConfig.mjs`), "providerMappings");

// Every icon an omp model resolves to: by model id first, then by provider id (as the extension does).
const used = new Set<string>();
const unmatched: string[] = [];
let modelCount = 0;
for (const provider of getBundledProviders()) {
	for (const model of getBundledModels(provider)) {
		modelCount++;
		const rule = match(modelRules, model.id) ?? match(providerRules, provider);
		if (rule) used.add(rule.icon);
		else unmatched.push(`${provider}/${model.id}`);
	}
}
if (used.size > MAX_ASSETS) throw new Error(`${used.size} icons exceed Discord's ${MAX_ASSETS} Art Assets`);

// Prefer the colored variant; fall back to the mono icon drawn for dark backgrounds.
const listing = (await (
	await fetch(`https://data.jsdelivr.com/v1/packages/npm/@lobehub/icons-static-png@${STATIC_PNG_VERSION}?structure=flat`)
).json()) as { files: { name: string }[] };
const darkPngs = new Set(listing.files.map((file) => file.name).filter((name) => name.startsWith("/dark/")));

rmSync(ASSETS_DIR, { recursive: true, force: true });
mkdirSync(ASSETS_DIR, { recursive: true });
const shipped = new Map<string, string>(); // lobe icon dir -> Discord asset key
for (const icon of [...used].sort()) {
	const key = icon.toLowerCase();
	const file = [`/dark/${key}-color.png`, `/dark/${key}.png`].find((name) => darkPngs.has(name));
	if (!file) {
		console.warn(`no PNG for ${icon}; models using it get no logo`);
		continue;
	}
	const png = await fetch(`https://cdn.jsdelivr.net/npm/@lobehub/icons-static-png@${STATIC_PNG_VERSION}${file}`);
	if (!png.ok) throw new Error(`${file}: HTTP ${png.status}`);
	writeFileSync(join(ASSETS_DIR, `${key}.png`), Buffer.from(await png.arrayBuffer()));
	shipped.set(icon, key);
}

// Rules keep lobe's order so precedence matches; an icon without a shipped asset maps to null (no badge, never a wrong one).
const toEntry = (rule: Rule) => `\t[${JSON.stringify(rule.keywords)}, ${JSON.stringify(shipped.get(rule.icon) ?? null)}],`;
writeFileSync(
	GENERATED_FILE,
	`// Generated by scripts/sync-model-icons.ts from @lobehub/icons@${LOBE_ICONS_VERSION}. Do not edit by hand.
// Each rule: [keyword regexes (case-insensitive), Discord Art Asset key or null when no logo is shipped].

export type IconRule = readonly [keywords: readonly string[], key: string | null];

/** Matched against the model id, first hit wins. */
export const MODEL_ICON_RULES: readonly IconRule[] = [
${modelRules.map(toEntry).join("\n")}
];

/** Fallback matched against the provider id when no model rule hits. */
export const PROVIDER_ICON_RULES: readonly IconRule[] = [
${providerRules.map(toEntry).join("\n")}
];
`,
);

console.log(`${modelCount} omp models -> ${used.size} icons, ${shipped.size} shipped as assets/models/*.png`);
console.log(`${unmatched.length} models without a logo, e.g. ${unmatched.slice(0, 8).join(", ")}`);

// What to change in the Developer Portal: Discord lists an application's Art Assets publicly.
const clientId = process.env.OMP_DISCORD_CLIENT_ID ?? "1566329796068384808";
const assetsResponse = await fetch(`https://discord.com/api/v10/oauth2/applications/${clientId}/assets`);
if (assetsResponse.ok) {
	const uploaded = new Set(((await assetsResponse.json()) as { name: string }[]).map((asset) => asset.name));
	const local = readdirSync(ASSETS_DIR).map((file) => file.replace(/\.png$/, ""));
	console.log(`upload to Art Assets: ${local.filter((key) => !uploaded.has(key)).join(", ") || "(none)"}`);
	console.log(`delete from Art Assets (no longer used): ${[...uploaded].filter((key) => !local.includes(key)).join(", ") || "(none)"}`);
} else {
	console.warn(`could not list Art Assets of ${clientId}: HTTP ${assetsResponse.status}`);
}
